function skillsInstallCmd(profile) {
  return `${SKILL_CMD} ${REPO} -a ${profile}`;
}

function getInstallCommands(provider) {
  if (provider.install) return provider.install();
  if (provider.profile) return [skillsInstallCmd(provider.profile)];
  return [];
}

function getUninstallCommands(provider) {
  if (provider.uninstall) return provider.uninstall();
  if (provider.profile) return [`${SKILL_REMOVE_CMD} pordee`];
  return [];
}

function run(cmd, dryRun) {
  if (dryRun) {
    console.log(`  [dry-run] ${cmd}`);
    return true;
  }
  try {
    execSync(cmd, { stdio: 'inherit' });
    return true;
  } catch (err) {
    console.error(`  failed: ${cmd}`);
    return false;
  }
}

function readRule() {
  if (!exists(RULE_SOURCE)) {
    console.error(`Rule source missing: ${RULE_SOURCE}`);
    return '';
  }
  return fs.readFileSync(RULE_SOURCE, 'utf8');
}

function stripMarkerBlock(text) {
  const lines = text.split('\n');
  const out = [];
  let inside = false;
  for (const line of lines) {
    if (line.trim() === MARKER_START) {
      inside = true;
      continue;
    }
    if (line.trim() === MARKER_END) {
      inside = false;
      continue;
    }
    if (!inside) out.push(line);
  }
  // Remove extra blank lines left by removed block.
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

function buildBlock(ruleText) {
  return [MARKER_START, MARKER_NOTE, '', ruleText.trim(), '', MARKER_END].join('\n');
}

function writeRuleFile(destPath, ruleText, dryRun) {
  if (dryRun) {
    console.log(`  [dry-run] write ${destPath}`);
    return;
  }
  fs.mkdirSync(path.dirname(destPath), { recursive: true });
  fs.writeFileSync(destPath, ruleText, 'utf8');
  console.log(`  wrote ${destPath}`);
}

function appendRuleFile(destPath, ruleText, dryRun) {
  if (dryRun) {
    console.log(`  [dry-run] append to ${destPath}`);
    return;
  }
  fs.mkdirSync(path.dirname(destPath), { recursive: true });
  let existing = '';
  if (exists(destPath)) {
    existing = fs.readFileSync(destPath, 'utf8');
    existing = stripMarkerBlock(existing);
    if (existing && !existing.endsWith('\n')) existing += '\n';
  }
  const block = buildBlock(ruleText);
  fs.writeFileSync(destPath, existing + '\n' + block + '\n', 'utf8');
  console.log(`  appended ${destPath}`);
}

function removeRuleFile(destPath, dryRun) {
  if (dryRun) {
    console.log(`  [dry-run] remove ${destPath}`);
    return;
  }
  if (!exists(destPath)) return;
  const content = fs.readFileSync(destPath, 'utf8');
  if (content.includes(MARKER_START)) {
    const cleaned = stripMarkerBlock(content);
    if (cleaned.trim()) {
      fs.writeFileSync(destPath, cleaned + '\n', 'utf8');
      console.log(`  cleaned markers from ${destPath}`);
    } else {
      fs.unlinkSync(destPath);
      console.log(`  removed ${destPath}`);
    }
  } else {
    fs.unlinkSync(destPath);
    console.log(`  removed ${destPath}`);
  }
}

function installRules(provider, dryRun) {
  if (!provider.ruleDests || !provider.ruleDests.length) return;
  const ruleText = readRule();
  if (!ruleText) return;
  console.log(`  rules for ${provider.name}:`);
  for (const dest of provider.ruleDests) {
    if (dest.type === 'append') {
      appendRuleFile(dest.path, ruleText, dryRun);
    } else {
      writeRuleFile(dest.path, ruleText, dryRun);
    }
  }
}

function uninstallRules(provider, dryRun) {
  if (!provider.ruleDests || !provider.ruleDests.length) return;
  console.log(`  removing rules for ${provider.name}:`);
  for (const dest of provider.ruleDests) {
    removeRuleFile(dest.path, dryRun);
  }
}

function removeState(dryRun) {
  if (dryRun) {
    console.log(`  [dry-run] rm -rf ${PORDEE_STATE_DIR}`);
    return;
  }
  if (exists(PORDEE_STATE_DIR)) {
    fs.rmSync(PORDEE_STATE_DIR, { recursive: true, force: true });
    console.log(`  removed ${PORDEE_STATE_DIR}`);
  }
}

function printList() {
  console.log('pordee agent matrix');
  console.log('');
  const idWidth = Math.max(...PROVIDERS.map(p => p.id.length));
  const nameWidth = Math.max(...PROVIDERS.map(p => p.name.length));
  console.log(`${'id'.padEnd(idWidth)}  ${'name'.padEnd(nameWidth)}  profile      detected  auto-activate  install command`);
  console.log('-'.repeat(idWidth + nameWidth + 80));
  for (const p of PROVIDERS) {
    const detected = p.detect() ? 'yes' : 'no';
    const auto = p.auto ? 'yes' : 'no';
    const profile = (p.profile || '-').padEnd(11);
    const cmds = getInstallCommands(p).join(' && ');
    console.log(`${p.id.padEnd(idWidth)}  ${p.name.padEnd(nameWidth)}  ${profile}  ${detected.padEnd(8)} ${auto.padEnd(14)} ${cmds}`);
  }
}

function printHelp() {
  console.log(`pordee installer

One-line install:
  curl -fsSL https://raw.githubusercontent.com/kerlos/pordee/main/install.sh | bash
  irm https://raw.githubusercontent.com/kerlos/pordee/main/install.ps1 | iex

Usage: node bin/install.js [flags]

Flags:
  --all              Install for every detected agent.
  --only <id>        Install for one agent. Repeatable.
  --dry-run          Print commands, change nothing.
  --list             Print agent matrix and exit.
  --with-init        Write always-on rule files for supported agents.
  --force            Re-run even if already installed.
  --uninstall        Remove pordee from detected agents + delete state.
  --help             Show this help.
`);
}

function parseArgs(argv) {
  const flags = {
    all: false,
    only: [],
    dryRun: false,
    list: false,
    withInit: false,
    force: false,
    uninstall: false,
    help: false
  };
  for (let i = 2; i < argv.length; i++) {
    const arg = argv[i];
    switch (arg) {
      case '--all':
        flags.all = true;
        break;
      case '--only':
        if (i + 1 >= argv.length) throw new Error('--only requires an agent id');
        flags.only.push(argv[++i]);
        break;
      case '--dry-run':
        flags.dryRun = true;
        break;
      case '--list':
        flags.list = true;
        break;
      case '--with-init':
        flags.withInit = true;
        break;
      case '--force':
        flags.force = true;
        break;
      case '--uninstall':
        flags.uninstall = true;
        break;
      case '--help':
      case '-h':
        flags.help = true;
        break;
      default:
        throw new Error(`Unknown flag: ${arg}`);
    }
  }
  return flags;
}

function main() {
  let flags;
  try {
    flags = parseArgs(process.argv);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }

  if (flags.help) {
    printHelp();
    return;
  }

  if (flags.list) {
    printList();
    return;
  }

  let selected;
  if (flags.only.length) {
    selected = flags.only
      .map(id => {
        const p = PROVIDERS.find(p => p.id === id);
        if (!p) throw new Error(`Unknown agent id: ${id}`);
        return p;
      });
  } else if (flags.all) {
    selected = PROVIDERS;
  } else {
    selected = PROVIDERS.filter(p => p.detect());
    if (selected.length === 0) {
      console.log('No supported agents detected.');
      console.log('Run with --all to try every known agent, or --only <id> for a specific one.');
      console.log('See --list for the full matrix.');
      return;
    }
  }

  if (flags.uninstall) {
    console.log('Uninstalling pordee...');
    let ranSkillsRemove = false;
    for (const p of selected) {
      console.log(`\n${p.name}:`);
      const cmds = getUninstallCommands(p);
      for (const cmd of cmds) {
        // Avoid duplicate npx skills remove calls.
        if (cmd === `${SKILL_REMOVE_CMD} pordee`) {
          if (ranSkillsRemove) continue;
          ranSkillsRemove = true;
        }
        run(cmd, flags.dryRun);
      }
      uninstallRules(p, flags.dryRun);
    }
    removeState(flags.dryRun);
    console.log('\nUninstall complete.');
    return;
  }

  console.log(flags.dryRun ? 'Dry-run install plan:' : 'Installing pordee...');
  for (const p of selected) {
    console.log(`\n${p.name}:`);
    const cmds = getInstallCommands(p);
    if (cmds.length === 0 && !p.ruleDests) {
      console.log('  nothing to do');
      continue;
    }
    for (const cmd of cmds) {
      run(cmd, flags.dryRun);
    }
    if (flags.withInit) {
      installRules(p, flags.dryRun);
    }
  }

  console.log('\nDone.');
  if (!flags.withInit) {
    console.log('Tip: use --with-init to drop always-on rule files into this repo.');
  }
}

main();
